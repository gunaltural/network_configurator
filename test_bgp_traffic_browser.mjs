import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)('playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||undefined,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1500,height:1050}}),errors=[];
const base=process.env.SMOKE_URL||'http://127.0.0.1:8147';
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(base+'/');
 await page.locator('#v3TechGrid button').filter({has:page.locator('h3',{hasText:'BGP'})}).click();
 assert.equal(await page.locator('#bgpMaxPrefix').isChecked(),false);
 await page.locator('#bgpAddUpstream').click();
 await page.locator('[data-bgp-device="isp3"][data-bgp-connected="false"]').waitFor();
 assert.equal(await page.locator('[data-bgp-connection]').count(),2);
 await page.locator('#bgpAddTrafficPolicy').click();
 const rule=page.locator('[data-traffic-policy="0"]');
 await rule.locator('[data-policy-field="localPreference"]').fill('333');
 await rule.locator('[data-policy-field="prefixes"]').fill('198.18.255.1/32');
 await rule.locator('[data-policy-field="enabled"]').check();
 await page.waitForFunction(()=>document.getElementById('output').textContent.includes('local-preference 333'));
 const displayed=await page.locator('#output').textContent();
 await page.locator('#outputCompare').click();await page.waitForURL('**/config-compare');
 assert.equal(await page.locator('#leftText').inputValue(),displayed);
 assert.equal(await page.locator('#rightText').inputValue(),'');
 await page.goto(base+'/?resume=1');await page.locator('#bgpTrafficPolicyRows [data-traffic-policy="0"]').waitFor();
 assert.equal(await page.locator('[data-traffic-policy="0"] [data-policy-field="localPreference"]').inputValue(),'333');
 await page.evaluate(()=>window.NetworkWorkspaceProject.prepareWorkspaceSimulation());
 await page.goto(base+'/network-lab?workspace=1');await page.locator('#wbPolicies').click();
 const outbound=page.locator('#syntheticOutboundPanel input[data-policy="localPreference"]').first();
 assert.ok(!(await page.locator('#wbPoliciesPanel').textContent()).includes('undefined'));
 assert.equal(await outbound.inputValue(),'333','Defaults must come from the Design rule, not a fixed value');
 await outbound.fill('777');
 assert.ok(!(await page.locator('#labMap [data-path-decision="BGP"]').textContent()).includes('777'),'Draft parameters do not apply before the button is pressed');
 await page.locator('#syntheticApplyOutbound').click();
 assert.match(await page.locator('#labMap [data-path-decision="BGP"]').textContent(),/777/);
 await page.locator('#syntheticInboundTab').click();
 assert.equal(await page.locator('#syntheticOutboundPanel').isHidden(),true);
 const inbound=page.locator('#syntheticInboundPanel input').first(),importedPrepend=await inbound.inputValue();
 await inbound.fill('4');await page.locator('#syntheticApplyInbound').click();
 await page.locator('#syntheticDefaultInbound').click();assert.equal(await inbound.inputValue(),importedPrepend);
 await page.locator('#syntheticOutboundTab').click();assert.equal(await outbound.inputValue(),'777');
 await page.locator('#syntheticDefaultOutbound').click();assert.equal(await outbound.inputValue(),'333');
 assert.match(await page.locator('#labMap [data-path-decision="BGP"]').textContent(),/333/);
 await page.screenshot({path:'/tmp/bgp-direction-parameters.png'});
 await page.evaluate(()=>{localStorage.clear();sessionStorage.clear();});
 await page.goto(base+'/network-lab?from=design');await page.locator('#wbPolicies').click();
 const pilotOutbound=page.locator('#syntheticOutboundPolicies input[data-link="wan1"]'),pilotDefault=await pilotOutbound.inputValue();
 await pilotOutbound.fill('888');await page.locator('#syntheticApplyOutbound').click();
 assert.equal(await page.evaluate(()=>window.SyntheticLab.evaluate().routes[0].selected.localPreference),888);
 await page.locator('#syntheticInboundTab').click();
 const pilotInbound=page.locator('#syntheticInboundPolicies input[data-link="wan1"]'),pilotPrepend=await pilotInbound.inputValue();
 await pilotInbound.fill('4');await page.locator('#syntheticApplyInbound').click();await page.locator('#syntheticDefaultInbound').click();
 assert.equal(await pilotInbound.inputValue(),pilotPrepend);
 assert.equal(await page.evaluate(()=>window.SyntheticLab.evaluate().routes[0].selected.localPreference),888);
 await page.locator('#syntheticOutboundTab').click();await page.locator('#syntheticDefaultOutbound').click();assert.equal(await pilotOutbound.inputValue(),pilotDefault);
 assert.deepEqual(errors,[]);
 console.log('Chromium BGP: policy editing, unconnected router, exact Compare baseline, persistence, separate directions and Design-derived apply/defaults passed.');
}finally{await browser.close();}
