"""Explicit opt-in, loopback-only *research demo* for original scratch weights.

Not wired into Network Configurator, production, Design or Simulation.
Start with: python -m research.network_lm.demo_api --checkpoint /tmp/network-state-probe.pt
"""
from argparse import ArgumentParser
from functools import lru_cache
from pathlib import Path
import os
import re

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel, ConfigDict, Field

from .inference import load_probe, predict

app = FastAPI(
    title="Network AI / Scratch State Probe — Research Preview",
    description="Synthetic-state classifier, not network diagnosis",
    docs_url=None, redoc_url=None, openapi_url=None,
)

_ID = re.compile(r"^[A-Za-z0-9_.:-]{1,64}$")

class ObservationRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    observation: str = Field(min_length=1, max_length=480)
    device: str = Field(default="unspecified", min_length=1, max_length=64)
    evidence_id: str = Field(default="manual-1", min_length=1, max_length=64)


def _enabled():
    return os.getenv("SCRATCH_DEMO_ENABLED") == "1"


@lru_cache(maxsize=2)
def _cached_local_model(path):
    return load_probe(path)


@app.get("/health")
def health():
    # Health is not a real-model evaluation or a success claim.
    return {"service": "research-scratch-demo",
            "enabled": _enabled(),
            "engineering_verified": False,
            "production_ready": False}


@app.get("/")
def home():
    if not _enabled():
        raise HTTPException(404, "Research demo is disabled")
    return FileResponse(Path(__file__).with_name("demo.html"),
                        media_type="text/html")


@app.post("/api/research/predict")
def classify(request: ObservationRequest):
    if not _enabled():
        raise HTTPException(503, "Scratch demo disabled by default")
    if not _ID.fullmatch(request.device) or not _ID.fullmatch(request.evidence_id):
        raise HTTPException(422, "Invalid research source identifier")
    checkpoint = os.getenv("SCRATCH_DEMO_CHECKPOINT", "").strip()
    if not checkpoint:
        raise HTTPException(503, "No locally generated research checkpoint configured")
    try:
        model, tokenizer = _cached_local_model(checkpoint)
    except (OSError, ValueError, KeyError, TypeError, RuntimeError) as exc:
        # No raw PyTorch errors, paths, inputs or checkpoint contents in API text.
        raise HTTPException(503, "Checkpoint unavailable or invalid") from None
    try:
        result = predict(model, tokenizer, request.observation)
    except ValueError:
        raise HTTPException(422, "Only a short, non-secret single-line observation is allowed")
    # User-provided coordinates are echoed as *unverified* references, never as
    # authenticated CLI citations or proof that the device ever produced them.
    result["source"] = {
        "device": request.device,
        "evidence_id": request.evidence_id,
        "provenance": "unverified-user-submitted-observation",
    }
    return result


def parser():
    ap = ArgumentParser(description=__doc__)
    ap.add_argument("--checkpoint", required=True,
                    help="Trusted local research checkpoint generated by state_probe")
    ap.add_argument("--port", type=int, default=8766)
    return ap


if __name__ == "__main__":
    arguments = parser().parse_args()
    if not 1024 <= arguments.port <= 65535:
        raise SystemExit("Port must be in 1024..65535")
    os.environ["SCRATCH_DEMO_ENABLED"] = "1"
    os.environ["SCRATCH_DEMO_CHECKPOINT"] = arguments.checkpoint
    import uvicorn
    # Explicit loopback only. To share or deploy would require separate
    # authentication, DLP, model calibration and independent acceptance.
    uvicorn.run(app, host="127.0.0.1", port=arguments.port, access_log=False)
