'use strict';
const assert=require('node:assert/strict');
require('./ai-topology-workspace.js');
require('./stp-engineering-v2.js');
require('./stp-network-analysis-v2.js');
require('./stp-synthetic-lab-v1.js');
require('./network-engineering-findings-v1.js');
const W=global.NetworkAITopology,L=global.NetworkSTPLabV1,E=global.NetworkSTPEngineeringV2,N=global.NetworkSTPNetworkV2,A=global.NetworkEngineeringFindingsV1;
const baseline=L.create();
const evaluate=ws=>{
 const ids=ws.nodes.map(n=>n.id);
 return A.run({workspace:ws,deviceIds:ids,technology:'STP',engineering:E.assess(ws,ids),network:N.analyze(ws,ids)});
};
const by=(r,id)=>r.findings.find(f=>f.id===id);
const ok=evaluate(baseline);
assert.equal(by(ok,'STP-ROOT-CONTAINMENT').status,'GOOD','Mapped core access guard is correctly configured');
assert.equal(by(ok,'STP-LOOP-RESILIENCE').status,'GOOD','Protected dual-homed uplinks are correctly identified');
assert.equal(by(ok,'STP-VTP-OFF').status,'GOOD','VTP off meaning is explained');
assert.match(by(ok,'STP-VTP-OFF').explanation,/does not relay/);
assert.equal(ok.counts.RISK,0,'Protected 3-device LAB baseline does not generate false protection risks');
assert.ok(by(ok,'STP-UDLD-PHYSICAL').status==='VERIFY','UDLD media cannot be proved by config alone');
const source=JSON.parse(JSON.stringify(baseline));
source.configs=source.configs.map(c=>({...c,source:'design',text:c.text.replace(/^\s*spanning-tree guard (?:root|loop)\n/gmi,'').replace(/^\s*udld port aggressive\n/gmi,'')}));
const noSafeguards=evaluate(source);
const root=by(noSafeguards,'STP-ROOT-CONTAINMENT'),loop=by(noSafeguards,'STP-LOOP-RESILIENCE');
assert.equal(root.status,'RISK','Disabled Root Guard on mapped Core-to-Access ports is recognized');
assert.equal(root.severity,'HIGH');
assert.match(root.observed,/0\/2 .*Root Guard/);
assert.ok(root.interfaces.some(x=>x.includes('LAB-CORE-A')),'Risk names the exact affected Core port');
assert.ok(root.interfaces.some(x=>x.includes('LAB-CORE-B')),'Both Core-to-Access sides evaluated');
assert.ok(root.evidence.some(x=>x.includes('interface TenGigabitEthernet1\/0\/1')),'Risk references actual interface stanza even when missing command');
assert.equal(loop.status,'RISK','Disabled Loop Guard on redundant Access uplinks is recognized');
assert.equal(loop.severity,'HIGH');
assert.ok(noSafeguards.counts.RISK>=2);
assert.ok(noSafeguards.findings.every(x=>x.expected&&x.observed&&x.networkImpact&&x.recommendation),'Common finding contract includes expected, observed, impact and action');
const oneProtected=JSON.parse(JSON.stringify(source));
oneProtected.configs=oneProtected.configs.map(c=>c.deviceId==='lab-access-a'?{
 ...c,text:c.text.replace('interface TenGigabitEthernet1/0/2','interface TenGigabitEthernet1/0/2\n spanning-tree guard loop')}:c);
assert.equal(by(evaluate(oneProtected),'STP-LOOP-RESILIENCE').status,'VERIFY','One protected alternate-candidate uplink is partial, not universally a fail');
const unmapped=JSON.parse(JSON.stringify(source));unmapped.links=unmapped.links.map(l=>({...l,aPort:'',bPort:''}));
const uncertain=evaluate(unmapped);
assert.equal(by(uncertain,'STP-ROOT-CONTAINMENT').status,'VERIFY','No false Root Guard missing assertion without port mapping');
assert.ok(!uncertain.findings.some(f=>f.id==='STP-LOOP-RESILIENCE'&&f.status==='RISK'),'No hard Loop Guard risk without mapped roles');
const partial=JSON.parse(JSON.stringify(source));partial.labMode=false;partial.configs=partial.configs.map(c=>({...c,source:'user'}));
assert.equal(by(evaluate(partial),'STP-ROOT-CONTAINMENT').status,'VERIFY','Incomplete user captures do not prove missing config');
const transparent=JSON.parse(JSON.stringify(baseline));transparent.configs[0].text=transparent.configs[0].text.replace('vtp mode off','vtp mode transparent');
const vtp=by(evaluate(transparent),'STP-VTP-TRANSPARENT');
assert.equal(vtp.status,'VERIFY');assert.match(vtp.explanation,/version 2 advertisements can still be forwarded/i);
const access=JSON.parse(JSON.stringify(source));access.configs=access.configs.map(c=>c.deviceId==='lab-access-a'?{
 ...c,text:c.text+'\ninterface GigabitEthernet1/0/10\n switchport mode access\n'}:c);
assert.equal(by(evaluate(access),'STP-EDGE-SAFETY').status,'RISK','Candidate endpoint access port without protections is recognized conditionally');
const extra=JSON.parse(JSON.stringify(baseline));
for(let i=3;i<10;i++)extra.nodes.push({id:'extra-'+i,hostname:'EXTRA-'+i,vendor:'Cisco IOS-XE',role:'unknown'});
const scopedIds=extra.nodes.map(n=>n.id);
const ten=A.run({workspace:extra,deviceIds:scopedIds,engineering:E.assess(extra,scopedIds),network:N.analyze(extra,scopedIds)});
assert.equal(ten.devices,10,'Ten device selection does not require a different algorithm');
assert.equal(by(ten,'DATA-CONFIG-COVERAGE').deviceIds.length,7,'Missing devices explicitly reported as coverage gap');
console.log('Evidence-first assessment: protected baseline, missing safeguards, role-based conditional risks, incomplete captures, VTP semantics and 10-device scale PASS');
