'use strict';
const assert=require('node:assert/strict');
require('./ai-topology-workspace.js');
require('./stp-engineering-v2.js');
require('./stp-network-analysis-v2.js');
require('./stp-operational-evidence-v1.js');
require('./stp-synthetic-lab-v1.js');
const api=global.NetworkAITopology,engineering=global.NetworkSTPEngineeringV2,operational=global.NetworkSTPOperationalV1,lab=global.NetworkSTPLabV1;
const data=lab.create();
assert.equal(data.nodes.length,3);
assert.equal(data.links.length,3);
assert.equal(data.configs.length,3);
assert.equal(data.showTech.length,3);
assert.ok(data.showTech.every(x=>x.synthetic===true));
const ids=data.nodes.map(x=>x.id),op=operational.assess(data,ids);
assert.equal(op.devices.length,3);
assert.ok(op.devices.every(x=>x.present&&x.syntheticOnly));
assert.ok(op.devices.every(x=>x.version?.value==='17.12.04'));
assert.ok(op.devices.every(x=>x.model?.value));
assert.equal(op.relationships.filter(x=>x.status==='CONFLICTING_ROOT_EVIDENCE').length,0);
assert.ok(op.relationships.some(x=>x.status==='ROOT_ID_MATCH'&&x.vlan===10));
assert.ok(op.relationships.some(x=>x.status==='ROOT_ID_MATCH'&&x.vlan===20));
const coreA=op.devices.find(x=>x.deviceId==='lab-core-a'),coreB=op.devices.find(x=>x.deviceId==='lab-core-b'),access=op.devices.find(x=>x.deviceId==='lab-access-a');
assert.equal(coreA.vlans.find(x=>x.vlan===10).isRoot,true);
assert.equal(coreB.vlans.find(x=>x.vlan===20).isRoot,true);
assert.equal(access.vlans.find(x=>x.vlan===10).isRoot,false);
assert.ok(access.vlans.flatMap(x=>x.ports).some(x=>x.role==='Altn'&&x.state==='BLK'));
const e=engineering.assess(data,ids);
operational.augment(e,op);
const d=e.devices.find(x=>x.id==='lab-core-a');
assert.equal(d.controls.find(x=>x.id==='STP-001').status,'OBSERVED');
assert.match(d.controls.find(x=>x.id==='STP-001').observed,/C9500-24Y4C/);
assert.equal(d.controls.find(x=>x.id==='STP-004').status,'LAB_OBSERVED');
assert.equal(d.controls.find(x=>x.id==='STP-012').status,'LAB_OBSERVED');
assert.equal(d.controls.find(x=>x.id==='STP-015').status,'LAB_OBSERVED');
assert.equal(d.controls.find(x=>x.id==='STP-016').status,'LAB_OBSERVED');
const full=global.NetworkSTPNetworkV2.analyze(data,ids);
assert.equal(full.deviceCount,3);
assert.equal(full.links.length,3);
const sample=api.analysisEvidenceBatches(data,ids).flat();
assert.ok(sample.some(x=>x.text.includes('SYNTHETIC LAB verification output')));
assert.ok(sample.some(x=>x.text.includes('proposed configuration')));
const device='lab-core-a';
const live=api.addShowTech(data,device,'===== show version =====\nCisco IOS XE Software, Version 17.15.01\nModel Number : C9500-24Y4C','real-showversion.txt',false);
assert.equal(live.showTech.filter(c=>c.deviceId===device).length,2);
assert.equal(live.showTech.filter(c=>c.deviceId===device&&c.synthetic===false).length,1);
assert.equal(data.showTech.filter(c=>c.deviceId===device).length,1,'Original fixture remains unchanged');
assert.ok(operational.assess(live,[device]).devices[0].captures.some(x=>!x.synthetic));
const replacement=api.addShowTech(live,device,'===== show version =====\nCisco IOS XE Software, Version 17.15.02','real-showversion.txt');
assert.equal(replacement.showTech.filter(c=>c.deviceId===device).length,2);
const removed=api.removeShowTech(replacement,device,'real-showversion.txt');
assert.equal(removed.showTech.filter(c=>c.deviceId===device).length,1);
const without=api.setShowTech(data,device,'','removed.txt');
assert.equal(without.showTech.some(c=>c.deviceId===device),false);
const noOp=operational.assess({nodes:data.nodes,showTech:[]},ids);
assert.ok(noOp.devices.every(x=>!x.present));
const noEvidence=engineering.assess({...data,showTech:[]},ids);
operational.augment(noEvidence,noOp);
assert.equal(noEvidence.devices.find(x=>x.id===device).controls.find(x=>x.id==='STP-004').status,'DESIGN_REVIEW');
console.log('STP operational evidence: independent Design/Show Tech, 3-device synthetic LAB, real upload provenance, root correlation and partial evidence PASS');
